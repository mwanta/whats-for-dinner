"""Build the recipe catalog and interactions, and write the matching report.

    python -m dinner_ml.data.build_catalog

Outputs (data/processed/, gitignored):
    recipes.parquet             clean recipes + per-serving EAA estimates
    interactions.parquet        (user_id, recipe_id, rating, timestamp)
    ingredient_matches.parquet  every distinct ingredient -> USDA food
Report (checked in): reports/ingredient_matching.md
"""
import collections
import time

import pandas as pd

from dinner_ml.data.eaa import EAA_COLUMNS, recipe_eaa
from dinner_ml.data.foodcom import load_interactions, load_recipes
from dinner_ml.data.ingredients import IngredientMatcher, Match
from dinner_ml.data.usda import load_usda
from dinner_ml.paths import ML_ROOT, PROCESSED_DIR

REPORT_PATH = ML_ROOT / "reports" / "ingredient_matching.md"

# WHO/FAO/UNU 2007 adult scoring pattern, mg per g protein. Used here only to
# sanity-check estimates and find each recipe's limiting amino acid.
WHO_PATTERN_MG_PER_G = {
    "histidine": 15, "isoleucine": 30, "leucine": 59, "lysine": 45,
    "methionine+cystine": 22, "phenylalanine+tyrosine": 38,
    "threonine": 23, "tryptophan": 6, "valine": 39,
}


def per_gram_protein(catalog: pd.DataFrame) -> pd.DataFrame:
    """The nine EAA scores in mg per g protein, with the WHO paired groups combined."""
    g = catalog.protein_g
    out = pd.DataFrame(index=catalog.index)
    for aa in ("histidine", "isoleucine", "leucine", "lysine", "threonine", "tryptophan", "valine"):
        out[aa] = catalog[f"{aa}_mg"] / g
    out["methionine+cystine"] = (catalog.methionine_mg + catalog.cystine_mg) / g
    out["phenylalanine+tyrosine"] = (catalog.phenylalanine_mg + catalog.tyrosine_mg) / g
    return out


def match_all(recipes: pd.DataFrame, matcher: IngredientMatcher) -> tuple[dict[str, Match], collections.Counter]:
    counts = collections.Counter(name for names in recipes.ingredients for name in names)
    return {name: matcher.match(name) for name in counts}, counts


def write_report(catalog, dropped, n_raw, matches, counts, interactions) -> str:
    total = sum(counts.values())
    by_source = collections.Counter()
    for name, n in counts.items():
        m = matches[name]
        by_source[m.source if m.matched else "unmatched"] += n

    lines = ["# Ingredient matching report", "", "Generated by `python -m dinner_ml.data.build_catalog`.", ""]
    lines += ["## Recipes", "", f"- Raw recipes: {n_raw:,}"]
    lines += [f"- Dropped, {k.replace('_', ' ')}: {v:,}" for k, v in dropped.items()]
    lines += [f"- **Kept: {len(catalog):,}**", ""]

    lines += ["## Ingredient uses matched to USDA", "", "| Source | Uses | Share |", "|---|---:|---:|"]
    for src in ("alias", "fuzzy", "partial", "unmatched"):
        lines.append(f"| {src} | {by_source[src]:,} | {by_source[src] / total:.1%} |")
    lines.append(f"| distinct names | {len(counts):,} | |")
    lines.append("")

    has = catalog.has_eaa
    lines += ["## Recipe-level coverage", ""]
    lines.append(f"- Recipes with an EAA estimate: {has.sum():,} ({has.mean():.1%})")
    for t in (1.0, 0.9, 0.75):
        share = (catalog.match_rate >= t).mean()
        lines.append(f"- Recipes with ≥{t:.0%} of ingredients matched: {share:.1%}")
    lines.append(f"- Median share of protein weight from imputed USDA profiles: {catalog.imputed_protein_share.median():.1%}")
    methods = catalog.eaa_method.value_counts()
    lines.append(f"- Estimated by mass balance: {methods.get('mass_balance', 0):,}; equal-mass fallback: {methods.get('equal_mass', 0):,}")
    err = catalog.fit_kcal_error.dropna()
    lines.append(
        f"- Mass-balance fit, calorie error vs. stated: median {err.median():.1%}, "
        f"90th percentile {err.quantile(0.9):.1%}"
    )
    cov = catalog.protein_coverage[catalog.protein_g >= 5]
    lines.append(
        f"- Protein coverage (fitted / stated protein, recipes ≥5 g): median {cov.median():.0%}; "
        f"below 50%: {(cov < 0.5).mean():.1%}. Low coverage almost always means Food.com's ingredient "
        "list is missing the main protein, which is usually named in the title."
    )
    lines.append("")
    lines += ["| EAA quality | Recipes | Meaning |", "|---|---:|---|"]
    meaning = {
        "high": "every ingredient matched, fit explains 70–130% of stated protein; use for the optimizer",
        "medium": "≥80% matched, fit explains 50–150% of stated protein",
        "low": "estimate exists but an ingredient (often the main protein) is unmatched or missing from the list",
        "none": "no estimate",
    }
    tiers = catalog.eaa_quality.value_counts()
    for tier, text in meaning.items():
        lines.append(f"| {tier} | {tiers.get(tier, 0):,} | {text} |")
    lines.append("")

    scored = catalog[(catalog.eaa_quality == "high") & (catalog.protein_g >= 5)]
    per_g = per_gram_protein(scored)
    ratio = per_g.div(pd.Series(WHO_PATTERN_MG_PER_G))
    lines += [
        "## Sanity check: amino-acid profile by category",
        "",
        "High-quality recipes with ≥5 g protein per serving. Reference values for single foods:",
        "meat and fish ~85–90 mg lysine/g protein, legumes ~65–70, wheat ~20–30. Mixed recipes",
        "should land between their main ingredients. \"Below WHO\" means at least one of the nine",
        "EAAs is under the WHO 2007 scoring pattern per gram of protein.",
        "",
        "| Category | Recipes | Lysine mg/g protein | Below WHO pattern | Most common limiting AA (when below) |",
        "|---|---:|---:|---:|---|",
    ]
    for cat in ["Chicken Breast", "Meat", "Pork", "Beans", "Lentil", "Vegan", "Rice", "Breads", "Yeast Breads", "Dessert"]:
        sel = scored.category == cat
        if sel.sum() < 20:
            continue
        below = ratio[sel].min(axis=1) < 1.0
        limiting = ratio[sel][below].idxmin(axis=1).value_counts()
        top = limiting.index[0] if len(limiting) else "—"
        lines.append(f"| {cat} | {sel.sum():,} | {per_g.lysine[sel].median():.0f} | {below.mean():.0%} | {top} |")
    lines.append("")

    lines += [
        "## Interactions",
        "",
        f"- Interactions (user, recipe): {len(interactions):,}",
        f"- Users: {interactions.user_id.nunique():,}",
        f"- Users with ≥5 interactions: {(interactions.user_id.value_counts() >= 5).sum():,}",
        f"- Reviews without a star rating: {interactions.rating.isna().mean():.1%}",
        "",
    ]

    worklist = [(n, name, matches[name]) for name, n in counts.most_common() if not matches[name].matched][:60]
    lines += [
        "## Most common unmatched ingredients",
        "",
        "Candidates for `dinner_ml/data/ingredient_aliases.csv`. The best fuzzy guess is shown for reference.",
        "",
        "| Uses | Ingredient | Best guess | Score |",
        "|---:|---|---|---:|",
    ]
    for n, name, m in worklist:
        lines.append(f"| {n:,} | {name} | {m.description or '—'} | {m.score:.2f} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    t0 = time.time()
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)

    usda = load_usda()
    recipes, dropped = load_recipes()
    n_raw = len(recipes) + sum(dropped.values())
    print(f"recipes: {len(recipes):,} kept of {n_raw:,} ({time.time() - t0:.0f}s)")

    matcher = IngredientMatcher(usda)
    matches, counts = match_all(recipes, matcher)
    print(f"matched {len(matches):,} distinct ingredients ({time.time() - t0:.0f}s)")

    eaa = recipe_eaa(recipes, matches, usda)
    catalog = recipes.join(eaa, on="recipe_id")
    interactions = load_interactions(catalog.recipe_id)

    catalog.to_parquet(PROCESSED_DIR / "recipes.parquet", index=False)
    interactions.to_parquet(PROCESSED_DIR / "interactions.parquet", index=False)
    pd.DataFrame(
        [
            {"ingredient": k, "uses": counts[k], "fdc_id": m.fdc_id, "usda_description": m.description,
             "score": m.score, "source": m.source, "matched": m.matched}
            for k, m in matches.items()
        ]
    ).sort_values("uses", ascending=False).to_parquet(PROCESSED_DIR / "ingredient_matches.parquet", index=False)

    REPORT_PATH.write_text(write_report(catalog, dropped, n_raw, matches, counts, interactions))
    print(f"wrote {PROCESSED_DIR} and {REPORT_PATH.relative_to(ML_ROOT)} ({time.time() - t0:.0f}s)")


if __name__ == "__main__":
    main()
